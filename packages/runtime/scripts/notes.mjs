import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { execSync } from "node:child_process";

const repo = resolve(import.meta.dirname, "../../..");
const rd = (f) => (existsSync(`results/${f}`) ? JSON.parse(readFileSync(`results/${f}`, "utf8")) : null);
const gates = rd("gates.json"), diag = rd("diag.json"), diag2 = rd("diag2.json"), bench = rd("bench.json"), browsers = rd("browsers.json");
