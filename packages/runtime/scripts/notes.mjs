const e = (x, d = 2) => (x === 0 ? "0" : Number(x).toExponential(d));
const f = (x, d = 1) => Number(x).toFixed(d);
const commit = execSync("git rev-parse --short HEAD", { cwd: repo }).toString().trim();
const sdkSize = execSync("node scripts/size-check.mjs", { cwd: resolve(repo, "packages/sdk") }).toString();
const runtimeSize = existsSync("dist/index.js") ? readFileSync("dist/index.js").length : "(not built)";
const ulps = (maxAbs, ref) => { const v = Math.abs(ref); if (v === 0) return "-"; const ulp = 2 ** (Math.floor(Math.log2(v)) - 10); return f(maxAbs / ulp, 1); };

