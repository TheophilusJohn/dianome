// Copies the Phase 4 privacy band (server/probes/results: the original 40k-token linear probe + inversion decoder
// from band.json, and the 500k-token linear probe from linear-500k.json) into data/privacy-band.<model>.json,
// one row per boundary. The planner and the split demo read this file; regenerate after a probes rerun.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const repo = resolve(import.meta.dirname, "../../..");
const band = JSON.parse(readFileSync(resolve(repo, "server/probes/results/band.json"), "utf8"));
const l500 = JSON.parse(readFileSync(resolve(repo, "server/probes/results/linear-500k.json"), "utf8"));
const by500 = new Map(l500.rows.map((r) => [r.boundary, r]));
const r4 = (x) => Math.round(x * 1e4) / 1e4;
const rows = band.rows.map((r) => {
  const l = by500.get(r.boundary);
  if (!l) throw new Error(`linear-500k has no boundary ${r.boundary}`);
  return {
    boundary: r.boundary,
    linear500k_top1: r4(l.linear_top1), linear500k_top5: r4(l.linear_top5),
    linear_top1: r4(r.linear_top1), linear_top5: r4(r.linear_top5),
    inversion_top1: r4(r.inversion_top1), inversion_top5: r4(r.inversion_top5),
    nn_top1: r4(r.nn_top1),
  };
});
const out = {
  model: band.meta.model,
  source: "server/probes/results/band.json (linear 40k + inversion) and linear-500k.json (linear 500k); docs/phase-4-notes.md",
  heldOut: { repo: band.meta.dataset.repo, config: band.meta.dataset.config, split: band.meta.dataset.split, tokens: band.meta.n_tokens, heldOutTokens: 10240 },
  coverage500k: r4(typeof l500.coverage === "number" ? l500.coverage : l500.rows[0].coverage),
  coverage40k: 0.8202,
  definition: "boundary i = the hidden state that leaves the client when N = i (the input to block i; 0 = token embeddings; L = the input to the final norm). top-1 = fraction of held-out positions whose input token a probe trained on that boundary recovers.",
  rows,
};
mkdirSync(resolve(import.meta.dirname, "../data"), { recursive: true });
const path = resolve(import.meta.dirname, `../data/privacy-band.${band.meta.model}.json`);
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${path}: ${rows.length} boundaries`);
// The same table as a TS module for the run entry (keeps the JSON out of the TS program and its declaration build).
const ts = resolve(import.meta.dirname, "../src/privacyBand.gen.ts");
writeFileSync(ts, `// Generated by scripts/gen-privacy-band.mjs from server/probes/results; do not edit. Same content as data/privacy-band.${band.meta.model}.json.\nexport const PRIVACY_BAND = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log(`wrote ${ts}`);
