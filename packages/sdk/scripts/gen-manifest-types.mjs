// Generates src/manifest.gen.ts from ../../schemas/manifest.v1.json.
// Dependency-free and specific to the constructs that schema uses: object/required/additionalProperties,
// $ref into $defs, enum, const, arrays, oneOf, propertyNames + additionalProperties (-> Record), primitives.
// `--check` exits 1 when the committed file is stale (run in `pnpm build`).
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../../schemas/manifest.v1.json");
const outPath = resolve(here, "../src/manifest.gen.ts");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

const pascal = (s) => s.replace(/(^|[_-])(\w)/g, (_, __, c) => c.toUpperCase());
const lit = (v) => JSON.stringify(v);

function typeOf(node, indent = "") {
  if (node.$ref) {
    const m = /^#\/\$defs\/(\w+)$/.exec(node.$ref);
    if (!m) throw new Error(`unsupported $ref ${node.$ref}`);
    return pascal(m[1]);
  }
  if ("const" in node) return lit(node.const);
  if (node.enum) return node.enum.map(lit).join(" | ");
  if (node.oneOf) return node.oneOf.map((n) => typeOf(n, indent)).join(" | ");
  switch (node.type) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "array": return `${typeOf(node.items, indent)}[]`;
    case "object": {
      if (node.properties) {
        const req = new Set(node.required ?? []);
        const lines = Object.entries(node.properties).map(([k, v]) => {
          const doc = v.description ? `${indent}  /** ${v.description.replace(/\*\//g, "* /")} */\n` : "";
          return `${doc}${indent}  ${/^\w+$/.test(k) ? k : lit(k)}${req.has(k) ? "" : "?"}: ${typeOf(v, indent + "  ")};`;
        });
        return `{\n${lines.join("\n")}\n${indent}}`;
      }
      if (node.additionalProperties && typeof node.additionalProperties === "object") {
        return `Record<string, ${typeOf(node.additionalProperties, indent)}>`;
      }
      return "Record<string, unknown>";
    }
    default: throw new Error(`unsupported node ${JSON.stringify(node).slice(0, 80)}`);
  }
}

let out = `// GENERATED by scripts/gen-manifest-types.mjs from schemas/manifest.v1.json — do not edit.\n// Regenerate with \`pnpm --filter dianome gen:types\`.\n\n`;
for (const [name, def] of Object.entries(schema.$defs)) {
  const doc = def.description ? `/** ${def.description} */\n` : "";
  out += `${doc}export type ${pascal(name)} = ${typeOf(def)};\n\n`;
}
// Top level: the schema is a base object plus a oneOf that splits it into a model manifest and a files manifest.
const base = typeOf({ type: "object", properties: schema.properties, required: schema.required });
out += `/** ${schema.description} */\nexport type ManifestBase = ${base};\n\n`;
const [model, files] = schema.oneOf;
const branch = (b) => `Required<Pick<ManifestBase, ${b.required.map(lit).join(" | ")}>>`;
const forbid = (b) => b.not.anyOf.flatMap((n) => n.required).map((k) => `${k}?: never`).join("; ");
out += `/** ${model.description} */\nexport type ModelManifest = ManifestBase & ${branch(model)} & { ${forbid(model)} };\n\n`;
out += `/** ${files.description} */\nexport type FilesManifest = ManifestBase & ${branch(files)} & { ${forbid(files)} };\n\n`;
out += `export type Manifest = ModelManifest | FilesManifest;\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(outPath, "utf8"); } catch {}
  if (current !== out) { console.error(`${outPath} is stale: run pnpm --filter dianome gen:types`); process.exit(1); }
  console.log("manifest.gen.ts up to date");
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath}`);
}
